"""Own profile, engapp:// URL scheme, request interception and downloads."""

import os
import sys
import tempfile

from PyQt6.QtCore import QBuffer, QByteArray, QIODevice, QTimer, QUrl
from PyQt6.QtWebEngineCore import (
    QWebEngineDownloadRequest,
    QWebEnginePage,
    QWebEngineProfile,
    QWebEngineUrlRequestInfo,
    QWebEngineUrlRequestInterceptor,
    QWebEngineUrlRequestJob,
    QWebEngineUrlScheme,
    QWebEngineUrlSchemeHandler,
)
from PyQt6.QtWidgets import QApplication

# Custom schemes must be registered BEFORE the QApplication is created.
SCHEME = QWebEngineUrlScheme(b"engapp")
SCHEME.setSyntax(QWebEngineUrlScheme.Syntax.Host)
SCHEME.setFlags(
    QWebEngineUrlScheme.Flag.SecureScheme | QWebEngineUrlScheme.Flag.LocalScheme
)
QWebEngineUrlScheme.registerScheme(SCHEME)

PAGES = {
    "/index": b"<html><head><title>Internal help</title></head><body>"
    b"<a id='csv' href='engapp://docs/data.csv' download='test.csv'>CSV</a>"
    b"<img src='engapp://docs/tracker.gif'></body></html>",
    "/data.csv": b"time_min;pressure_bar\n0;345.0\n30;344.2\n60;344.0\n",
}


class InternalContent(QWebEngineUrlSchemeHandler):
    """Serves content generated by Python (database, calculations, packaged files)."""

    def requestStarted(self, job: QWebEngineUrlRequestJob) -> None:
        path = job.requestUrl().path()
        if path not in PAGES:
            job.fail(QWebEngineUrlRequestJob.Error.UrlNotFound)
            return
        mime = b"text/csv" if path.endswith(".csv") else b"text/html"
        buf = QBuffer(parent=job)  # the job owns the buffer
        buf.setData(PAGES[path])
        buf.open(QIODevice.OpenModeFlag.ReadOnly)
        job.reply(QByteArray(mime), buf)


class Filter(QWebEngineUrlRequestInterceptor):
    """Runs outside the GUI thread: it only decides on and adjusts the request."""

    def interceptRequest(self, info: QWebEngineUrlRequestInfo) -> None:
        url = info.requestUrl()
        kind = info.resourceType().name
        if "tracker" in url.path():
            info.block(True)
            print(f"  interceptor: BLOCKED {url.path()} ({kind})")
        else:
            info.setHttpHeader(b"X-App", b"PyQt6Manual")
            print(f"  interceptor: allowed {url.path()} ({kind})")


def main() -> int:
    app = QApplication(sys.argv)
    profile = (
        QWebEngineProfile()
    )  # no name: "off-the-record" profile (nothing goes to disk)
    print("Off-the-record profile:", profile.isOffTheRecord())
    handler, request_filter = InternalContent(), Filter()
    profile.installUrlSchemeHandler(b"engapp", handler)
    profile.setUrlRequestInterceptor(request_filter)
    folder = tempfile.mkdtemp()

    def download(req: QWebEngineDownloadRequest) -> None:
        req.setDownloadDirectory(folder)
        print(f"  download requested: {req.downloadFileName()} ({req.mimeType()})")
        req.isFinishedChanged.connect(lambda: finished(req))
        req.accept()  # without accept(), the download is canceled

    def finished(req: QWebEngineDownloadRequest) -> None:
        path = os.path.join(req.downloadDirectory(), req.downloadFileName())
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
        print(
            f"  download {req.state().name}: {len(lines)} lines; last = "
            f"{lines[-1]!r}"
        )
        QTimer.singleShot(0, app.quit)

    profile.downloadRequested.connect(download)
    page = QWebEnginePage(profile)

    def on_loaded(ok: bool) -> None:
        print(f"loadFinished: {ok}; title: {page.title()!r}")
        page.runJavaScript("document.getElementById('csv').click()")

    page.loadFinished.connect(on_loaded)
    page.load(QUrl("engapp://docs/index"))
    QTimer.singleShot(12_000, app.quit)
    code = app.exec()
    del page  # the page must be destroyed before its profile
    return code


if __name__ == "__main__":
    sys.exit(main())
