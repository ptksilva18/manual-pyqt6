VERSION = QtCore.PYQT_VERSION_STR


def _value(member: enum.Enum) -> str:
    v = member.value
    if isinstance(member, enum.Flag) and v > 9:
        return f"0x{v:X}"
    return str(v)


def enum_table(enum_cls, items, title: str):
    """items: [(member_name, description)]; the qualified name is built by introspection."""
    qual = f"{enum_cls.__qualname__}"
    rows = []
    for name, desc in items:
        assert hasattr(enum_cls, name), f"{qual}.{name} does not exist in PyQt6 {VERSION}"
        rows.append([f"{qual}.{name}", _value(getattr(enum_cls, name)), desc])
    return tab(title, ["Member (full name in PyQt6)", "Value", "Use"], rows, [4100, 1000, 3971],
               font=16)


def _find(cls, short_name: str) -> str:
    """Finds the enum of 'cls' that contains the member 'short_name' (PyQt5 -> PyQt6 migration)."""
    found = []
    for attribute in dir(cls):
        obj = getattr(cls, attribute)
        if isinstance(obj, type) and issubclass(obj, enum.Enum) and short_name in obj.__members__:
            found.append(f"{obj.__qualname__}.{short_name}")
    assert len(found) == 1, f"{cls.__name__}.{short_name}: {found}"
    return found[0]


